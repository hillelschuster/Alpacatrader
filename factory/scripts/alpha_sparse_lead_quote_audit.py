#!/usr/bin/env python3
"""FULL-COVERAGE as-of NBBO audit of the programme's only internally positive lead.

The lead (learned_sparse_daily / learned_sparse_extension, stored h60 model, thr=0.03) was
reported on MINUTE-OPEN PROXY prices: +0.1417 %/day of the $3,000 book at 100 bps for the
once_h60 control and +0.1892 %/day for the repeat_h60 cadence. The only reason it stayed
unvalidated was that the as-of side-aware quote audit covered 77 of 143 fill pairs.

This script closes exactly that gap and nothing else:

* FULL QUOTE UNIVERSE: every fill is priced against the merged NBBO substrate -- the ranked
  SIP day cache first, then the read-only supplement roots (sparse_execution_frontier
  fetched_quotes, quote_completeness_audit quotes) and the panel-universe harvest
  quote_universe_acquire quotes. Primary prints KEEP FIRST; a supplement may only ADD a
  (symbol, ts_utc) print, never revise or replace one.
* BOTH BLOCKS (2023 validation, 250 sessions; late 2025-02..2026-05, 332 sessions) and
  BOTH CADENCES (once_h60 control, repeat_h60) of the SAME stored model and threshold.
* SAME FILLS: the trade sets are regenerated by the lead's own replay engine
  (``alpha_sparse_daily.replay_view``) on the SAME signals, and the reproduction of the
  stored proxy numbers is asserted to 1e-12 before a single quote is read.
* CAUSAL, SIDE-AWARE PRICING: entry at the ASK and exit at the BID, each from ONE
  observation of the latest raw print at/before the arrival clock (intent + 250 ms). No
  resting into a later print, no +-minute window, no future-quote selection, no widening
  of the 2 s freshness guard, no fallback to an older regular print. The print at the
  INTENT clock is recorded beside the arrival print for every fill.
* FILL STATUS, one of four:
    asked_supported - both legs priced fresh/valid/regular at arrival and the $1,000
        ticket fits the displayed depth at the entry ASK and at the exit BID. This is the
        only class that carries a quote-verified net.
    conditional - both legs priced, but the ticket exceeds the displayed depth on at least
        one leg: the price is observed, the capacity is not. Never known cash.
    no_match - the ticker has NO quote stream in ANY merged root for that session.
    unknown - a stream exists but the arrival print is stale (> 2 s), non-regular,
        invalid/crossed, or absent before the clock.
  conditional/no_match/unknown are all UNKNOWNs: they are charged the full $1,000 unit in
  a labelled lower bound exactly as the lead's own replay charges an UNKNOWN exit, never
  dropped and never zero.
* FEES: the lead's own convention -- a residual rung charged on BOTH legs, multiplicatively
  on the price (``alpha_quote_aware_frequency.net_usd``), with the quantity sized once at
  the highest reported rung so every rung is funded by the same share count.

Quotes measure the touch cost of a hypothetical market order. They are not exchange fills,
never a fill guarantee, and they cannot certify any fill the audit did not price.
"""

