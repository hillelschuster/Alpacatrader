def block_days() -> dict[str, list[str]]:
    """The lead's own block day lists (panel day files, protected days refused)."""
    files = sorted(p.stem for p in (PANEL_ROOT / "days").glob("????-??-??.parquet") if allowed(p.stem))
    out: dict[str, list[str]] = {}
    for day in files:
        if period(day) in ("validation", "confirmation"):
            out.setdefault(period(day), []).append(day)
    for block, expected in (("validation", 250), ("confirmation", 332)):
        if len(out.get(block, [])) != expected:
            raise SystemExit(f"[lead-quote-audit] expected {expected} {block} days, got {len(out.get(block, []))}")
    return out


# ----- trade sets (the lead's own replay, reproduced, never refitted) ----------
def lead_trade_sets(blocks: dict[str, list[str]]) -> tuple[dict[tuple[str, str], list[dict]], list[dict]]:
    """(block, view) -> the lead's own fills, regenerated from its stored signals."""
    signals = pl.read_parquet(PANEL_ROOT / "learned_sparse_daily" / "signals.parquet")
    out: dict[tuple[str, str], list[dict]] = {}
    reproduction: list[dict] = []
    for block, days in blocks.items():
        for name in LEAD_VIEWS:
            view = asd.VIEWS_BY_NAME[name]
            metrics, trades = asd.replay_view(asd.view_signals(signals, view), days, view, SELECT_COST)
            out[(block, name)] = trades
            stored = STORED_PROXY[(block, name)]
            checks = {
                "days": (metrics["days"], stored["days"]),
                "fills": (metrics["fills"], stored["fills"]),
                "known_fills": (metrics["known_fills"], stored["known_fills"]),
                "mean_daily_lower_bound": (metrics["mean_daily_lower_bound"], stored["mean_daily_lower_bound"]),
                "dollars_per_day": (metrics["dollars_per_day"], stored["dollars_per_day"]),
            }
            all_match = all(abs(a - b) <= PROXY_TOL for a, b in checks.values())
            reproduction.append(
                {
                    "block": block,
                    "view": name,
                    "all_match": bool(all_match),
                    "mismatch": (
                        {k: {"replayed": a, "stored": b} for k, (a, b) in checks.items() if abs(a - b) > PROXY_TOL}
                    ),
                    "replayed": {k: v for k, (v, _) in checks.items()},
                }
            )
            if not all_match:
                raise SystemExit(
                    f"[lead-quote-audit] {block}/{name} does not reproduce the stored lead: "
                    f"{reproduction[-1]['mismatch']}"
                )
    return out, reproduction


# ----- causal, side-aware as-of pricing ---------------------------------------
def leg_print(
    sq: aqf.SymbolQuotes | None, minute: int, day: str
) -> tuple[dict | None, str, dict | None, str]:
    """Causal side-aware print of one leg: the INTENT clock and the ARRIVAL clock.

    The intent print is the observation the policy saw when it decided (no age cap, it is
    a record of the state, not a fill). The arrival print is what a market order meets at
    intent + LATENCY_MS: ONE observation of the latest raw print at/before that clock,
    R-only, un-crossed, finite, and no older than the 2 s freshness guard. No resting to a
    later print and no fallback to an older regular print, exactly like
    ``alpha_quote_audit.asof_quote`` / ``alpha_quote_aware_frequency.entry_price_leg``.
    """
    intent_us = aqf.minute_us(day, minute)
    arrival_us = int(intent_us) + LATENCY_MS * 1000
    if sq is None:
        return None, "quote_not_acquired", None, "quote_not_acquired"
    iq, istatus = sq.latest_raw(intent_us)
    aq, astatus = sq.latest_raw(arrival_us)
    if aq is None:
        return iq, istatus, None, astatus
    if aq["age_s"] > MAX_AGE_S:
        return iq, istatus, None, "unknown_stale_but_valid_at_arrival"
    return iq, istatus, aq, "quoted"


def audit_fill(trade: dict, streams: dict[str, aqf.SymbolQuotes]) -> dict:
    """One fill: side-aware intent/arrival prints, fill status, net at every rung."""
    day, ticker = trade["day"], trade["ticker"]
    sq = streams.get(ticker)
    entry_iq, entry_istatus, entry_aq, entry_astatus = leg_print(sq, int(trade["entry_et"]), day)
    if trade["exit_et"] is None:
        exit_iq, exit_istatus = None, "unknown_pending_exit"
        exit_aq, exit_astatus = None, "unknown_pending_exit"
    else:
        exit_iq, exit_istatus, exit_aq, exit_astatus = leg_print(sq, int(trade["exit_et"]), day)
    record = {
        "day": day,
        "ticker": ticker,
        "entry_et": int(trade["entry_et"]),
        "exit_et": int(trade["exit_et"]) if trade["exit_et"] is not None else None,
        "proxy_gross": trade["gross"],
        "proxy_net": trade["net"],
        "proxy_net_usd": None if trade["net"] is None else ORDER_BUDGET * float(trade["net"]),
        "entry_stream_present": sq is not None,
        "entry_intent_status": entry_istatus,
        "entry_arrival_status": entry_astatus,
        "exit_intent_status": exit_istatus,
        "exit_arrival_status": exit_astatus,
        "entry_intent_ask": None if entry_iq is None else entry_iq["ask"],
        "entry_arrival_ask": None if entry_aq is None else entry_aq["ask"],
        "entry_arrival_bid": None if entry_aq is None else entry_aq["bid"],
        "exit_intent_bid": None if exit_iq is None else exit_iq["bid"],
        "exit_arrival_bid": None if exit_aq is None else exit_aq["bid"],
        "exit_arrival_ask": None if exit_aq is None else exit_aq["ask"],
        "entry_arrival_age_s": None if entry_aq is None else entry_aq["age_s"],
        "exit_arrival_age_s": None if exit_aq is None else exit_aq["age_s"],
        "entry_arrival_spread_bps": None if entry_aq is None else entry_aq["spread_bps"],
        "exit_arrival_spread_bps": None if exit_aq is None else exit_aq["spread_bps"],
        "entry_displayed_shares": None if entry_aq is None else entry_aq["ask_shares"],
        "exit_displayed_shares": None if exit_aq is None else exit_aq["bid_shares"],
    }
    for rung in RUNG_KEYS:
        record[f"net_usd_{rung}"] = None

    if sq is None:
        record["fill_status"] = STATUS_NO_MATCH
        record["status_detail"] = "no quote stream in the ranked cache or any supplement root"
        return record

    if entry_aq is None or exit_aq is None:
        reasons = {
            "entry": entry_astatus if entry_aq is None else "quoted",
            "exit": exit_astatus if exit_aq is None else "quoted",
        }
        record["fill_status"] = STATUS_UNKNOWN
        record["status_detail"] = ";".join(f"{leg}:{why}" for leg, why in reasons.items() if why != "quoted")
        return record

    entry_ask = float(entry_aq["ask"])
    exit_bid = float(exit_aq["bid"])
    record["touch_gross_bps"] = (exit_bid / entry_ask - 1.0) * 10_000.0
    record["latency_move_bps"] = (float(entry_aq["ask"]) / float(entry_iq["ask"]) - 1.0) * 10_000.0 if entry_iq is not None else None
    quantity = fee_funded_quantity(entry_ask, SIZING_RUNG_BPS)
    record["quantity"] = quantity
    entry_depth_ok = quantity <= float(entry_aq["ask_shares"])
    exit_depth_ok = quantity <= float(exit_aq["bid_shares"])
    record["entry_depth_supported"] = bool(entry_depth_ok)
    record["exit_depth_supported"] = bool(exit_depth_ok)
    if quantity < 1:
        record["fill_status"] = STATUS_UNKNOWN
        record["status_detail"] = "known_no_order_min_capital: the $1,000 ticket funds no share at the quoted ask"
        return record
    if not (entry_depth_ok and exit_depth_ok):
        short = "entry_and_exit_displayed_depth_short"
        if not entry_depth_ok and exit_depth_ok:
            short = "entry_displayed_depth_short"
        elif entry_depth_ok and not exit_depth_ok:
            short = "exit_displayed_depth_short"
        record["fill_status"] = STATUS_CONDITIONAL
        record["status_detail"] = (
            f"{short}: ticket {quantity} shares vs "
            f"{int(entry_aq['ask_shares'])} entry / {int(exit_aq['bid_shares'])} exit displayed"
        )
        return record
    record["fill_status"] = STATUS_SUPPORTED
    record["status_detail"] = "priced_fresh_at_arrival_both_legs_displayed_depth_covers_ticket"
    for rung in AUDIT_RUNGS_BPS:
        record[f"net_usd_{int(rung)}"] = aqf.net_usd(quantity, exit_bid, entry_ask, rung)
    return record


# ----- accounting -------------------------------------------------------------
def account(records: list[dict], days: list[str]) -> dict:
    """Per-basis aggregates for one (block, cadence): lower bound, coverage, diagnostics."""
    fills = len(records)
    supported = [r for r in records if r["fill_status"] == STATUS_SUPPORTED]
    unsupported = [r for r in records if r["fill_status"] != STATUS_SUPPORTED]
    both_legs_priced = [r for r in records if r["entry_arrival_status"] == "quoted" and r["exit_arrival_status"] == "quoted"]

    # Daily lower bound: every supported fill's quote net, every other fill the full
    # $1,000 unit (the lead's own UNKNOWN rule), over EVERY session of the block.
    daily: dict[str, dict] = {}
    for r in records:
        slot = daily.setdefault(r["day"], {"unknown_fills": 0})
        nets = [r[f"net_usd_{k}"] for k in RUNG_KEYS]
        if all(n is None for n in nets):
            slot["unknown_fills"] += 1
        else:
            for k, n in zip(RUNG_KEYS, nets):
                slot[f"known_{k}"] = slot.get(f"known_{k}", 0.0) + float(n)
    for day in days:
        daily.setdefault(day, {"unknown_fills": 0})

    lower: dict[str, float] = {}
    for k in RUNG_KEYS:
        lower[str(k)] = float(
            sum(slot.get(f"known_{k}", 0.0) for slot in daily.values())
            - ORDER_BUDGET * sum(slot["unknown_fills"] for slot in daily.values())
        )
    mean_daily = {k: v / len(days) for k, v in lower.items()}
    pct_per_day = {k: v / RESERVE_USD for k, v in mean_daily.items()}
    total_unknown = sum(slot["unknown_fills"] for slot in daily.values())

    touch = np.array([r["touch_gross_bps"] for r in both_legs_priced if r.get("touch_gross_bps") is not None]) if both_legs_priced else np.array([])
    entry_spread = np.array([r["entry_arrival_spread_bps"] for r in both_legs_priced if r.get("entry_arrival_spread_bps") is not None])
    exit_spread = np.array([r["exit_arrival_spread_bps"] for r in both_legs_priced if r.get("exit_arrival_spread_bps") is not None])
    entry_age = np.array([r["entry_arrival_age_s"] for r in both_legs_priced if r.get("entry_arrival_age_s") is not None])
    exit_age = np.array([r["exit_arrival_age_s"] for r in both_legs_priced if r.get("exit_arrival_age_s") is not None])
    latency_move = np.array([r["latency_move_bps"] for r in both_legs_priced if r.get("latency_move_bps") is not None])
    ticket = np.array(
        [
            float(r["quantity"]) * float(r["entry_arrival_ask"])
            for r in both_legs_priced
            if r.get("quantity") is not None and r.get("entry_arrival_ask") is not None
        ]
    )

    def _mean(a: np.ndarray) -> float | None:
        return float(np.mean(a)) if a.size else None

    verdict_100 = "SURVIVES" if mean_daily["100"] > 0 else ("REDUCED" if mean_daily["0"] > 0 else "DIES")
    statuses: dict[str, int] = {}
    for r in records:
        statuses[r["fill_status"]] = statuses.get(r["fill_status"], 0) + 1
    leg_reasons: dict[str, int] = {}
    for r in records:
        for leg, key in (("entry", "entry_arrival_status"), ("exit", "exit_arrival_status")):
            if r[key] != "quoted":
                leg_reasons[f"{leg}:{r[key]}"] = leg_reasons.get(f"{leg}:{r[key]}", 0) + 1

    first_day, last_day = days[0], days[-1]
    span_days = (date.fromisoformat(last_day) - date.fromisoformat(first_day)).days + 1
    return {
        "sessions": len(days),
        "session_span": {"first_day": first_day, "last_day": last_day, "calendar_days": span_days},
        "fills": fills,
        "days_with_a_fill": len({r["day"] for r in records}),
        "coverage": {
            "fills_with_both_legs_priced": len(both_legs_priced),
            "coverage_pct": (100.0 * len(both_legs_priced) / fills) if fills else None,
            "entry_legs_priced": sum(1 for r in records if r["entry_arrival_status"] == "quoted"),
            "exit_legs_priced": sum(1 for r in records if r["exit_arrival_status"] == "quoted"),
            "fills_with_a_quote_stream": sum(1 for r in records if r["entry_stream_present"]),
            "stream_coverage_pct": (100.0 * sum(1 for r in records if r["entry_stream_present"]) / fills) if fills else None,
        },
        "status_counts": statuses,
        "unknown_fills": len(unsupported),
        "unknown_share": (len(unsupported) / fills) if fills else None,
        "unknown_share_pct": (100.0 * len(unsupported) / fills) if fills else None,
        "quote_verified": {
            "asked_supported_fills": len(supported),
            "mean_net_usd_per_fill": {
                str(k): (float(np.mean([r[f"net_usd_{k}"] for r in supported])) if supported else None)
                for k in RUNG_KEYS
            },
            "supported_total_net_usd": {
                str(k): float(sum(r[f"net_usd_{k}"] for r in supported)) if supported else 0.0
                for k in RUNG_KEYS
            },
            "lower_bound_total_net_usd": lower,
            "lower_bound_usd_per_session": mean_daily,
            "lower_bound_pct_per_session_of_3000_book": pct_per_day,
            "lower_bound_usd_per_calendar_day_span": {
                k: v / span_days for k, v in lower.items()
            },
            "lower_bound_usd_per_year_252_sessions": {
                k: v * DAYS_PER_YEAR for k, v in mean_daily.items()
            },
            "unknown_full_loss_charge_usd": ORDER_BUDGET * total_unknown,
            "unknown_full_loss_charge_fills": total_unknown,
        },
        "diagnostics": {
            "mean_touch_gross_bps": _mean(touch),
            "median_touch_gross_bps": float(np.median(touch)) if touch.size else None,
            "mean_entry_spread_bps": _mean(entry_spread),
            "mean_exit_spread_bps": _mean(exit_spread),
            "mean_entry_arrival_age_s": _mean(entry_age),
            "mean_exit_arrival_age_s": _mean(exit_age),
            "mean_entry_latency_move_bps": _mean(latency_move),
            "ticket_notional_usd": {
                "mean": _mean(ticket),
                "min": float(np.min(ticket)) if ticket.size else None,
                "max": float(np.max(ticket)) if ticket.size else None,
                "order_budget_usd": ORDER_BUDGET,
                "note": (
                    "the entry outlay of the fee-funded share count at the 150 bps sizing "
                    "rung; it must sit just under the $1,000 ticket or the book accounting "
                    "is wrong"
                ),
            },
            "fills_where_arrival_print_differs_from_intent": sum(
                1
                for r in both_legs_priced
                if r["entry_arrival_ask"] is not None
                and r["entry_intent_ask"] is not None
                and abs(r["entry_arrival_ask"] - r["entry_intent_ask"]) > 1e-12
            ),
        },
        "unpriced_leg_reasons": dict(sorted(leg_reasons.items())),
        "verdict_rule": VERDICT_RULE,
        "verdict_at_100bps": verdict_100,
    }


# ----- driver -----------------------------------------------------------------
def run_audit(
    trade_sets: dict[tuple[str, str], list[dict]], roots: tuple[Path, ...], tag: str
) -> tuple[dict[tuple[str, str], list[dict]], dict[str, dict]]:
    """Audit every fill of every (block, cadence) over one merge root set.

    One ET day of merged quotes is resident at a time and every cadence is priced on it,
    so the corpus is never resident at once.
    """
    by_day: dict[str, list[tuple[tuple[str, str], dict]]] = {}
    for key, trades in trade_sets.items():
        for tr in trades:
            by_day.setdefault(tr["day"], []).append((key, tr))
    all_days = sorted(by_day)
    bad = [d for d in all_days if not allowed(d)]
    if bad:
        raise SystemExit(f"protected quote read refused: {bad}")
    day_tickers = {d: {tr["ticker"] for _, tr in rows} for d, rows in by_day.items()}

    records: dict[tuple[str, str], list[dict]] = {k: [] for k in trade_sets}
    root_files: dict[str, dict] = {}
    for n, day in enumerate(all_days, 1):
        frame = aqf.quote_day_frame(ROOT / "data", day, day_tickers[day], roots)
        streams = aqf.symbol_quotes(frame, day)
        primary = root_files.setdefault(
            "ranked_sip_day_cache", {"days_present": 0, "days_requested": 0}
        )
        primary["days_requested"] += 1
        if day_quote_path(ROOT / "data", day).exists():
            primary["days_present"] += 1
        for root in roots:
            entry = root_files.setdefault(str(root), {"days_present": 0, "days_requested": 0})
            entry["days_requested"] += 1
            if supplement_day_path(root, day).exists():
                entry["days_present"] += 1
        for key, tr in by_day[day]:
            records[key].append(audit_fill(tr, streams))
        del frame, streams
        if n % 25 == 0:
            print(f"[quotes:{tag}] {n}/{len(all_days)} days merged", flush=True)
    print(
        f"[quotes:{tag}] {len(all_days)} ET days merged over {len(roots) + 1} roots",
        flush=True,
    )
    return records, root_files


def baseline_comparison(
    merged: dict[tuple[str, str], list[dict]], primary_only: dict[tuple[str, str], list[dict]]
) -> dict:
    """What the full universe actually added over the primary-cache-only audit."""
    cells: dict[str, dict] = {}
    for key in sorted(merged):
        m, p = merged[key], primary_only[key]

        def both_priced(rs: list[dict]) -> int:
            return sum(
                1 for r in rs if r["entry_arrival_status"] == "quoted" and r["exit_arrival_status"] == "quoted"
            )

        def supported(rs: list[dict]) -> int:
            return sum(1 for r in rs if r["fill_status"] == STATUS_SUPPORTED)

        pm = {(r["day"], r["ticker"], r["entry_et"]): r for r in p}
        improved = unchanged = regressed = 0
        price_revised = 0
        for r in m:
            o = pm[(r["day"], r["ticker"], r["entry_et"])]
            rank = {STATUS_SUPPORTED: 3, STATUS_CONDITIONAL: 2, STATUS_UNKNOWN: 1, STATUS_NO_MATCH: 1}
            if rank[r["fill_status"]] > rank[o["fill_status"]]:
                improved += 1
            elif rank[r["fill_status"]] < rank[o["fill_status"]]:
                regressed += 1
            else:
                unchanged += 1
            if (
                o.get("net_usd_0") is not None
                and r.get("net_usd_0") is not None
                and abs(r["net_usd_0"] - o["net_usd_0"]) > 0.005
            ):
                price_revised += 1
        cells[f"{key[0]}/{key[1]}"] = {
            "primary_only_both_legs_priced": both_priced(p),
            "merged_both_legs_priced": both_priced(m),
            "primary_only_coverage_pct": 100.0 * both_priced(p) / len(m) if m else None,
            "merged_coverage_pct": 100.0 * both_priced(m) / len(m) if m else None,
            "primary_only_asked_supported": supported(p),
            "merged_asked_supported": supported(m),
            "fills_improved": improved,
            "fills_unchanged": unchanged,
            "fills_regressed": regressed,
            "supported_nets_revised_beyond_half_a_cent": price_revised,
        }
    return {
        "note": (
            "the SAME fills, the SAME rules, priced twice: once against the ranked SIP cache "
            "alone (the old audit's substrate) and once against the full merged universe. "
            "fills_improved/regressed compare the four-way status; a revised net on a fill "
            "that was already supported would mean a supplement print displaced a primary "
            "one, which the keep-first merge forbids"
        ),
        "cells": cells,
    }


