def fee_funded_quantity(price: float, rung_bps: float = SIZING_RUNG_BPS) -> int:
    """Integer shares the LEAD's $1,000 ticket funds at one price and residual rung.

    Deliberately local, not ``alpha_quote_aware_frequency.causal_quantity``: that helper
    sizes its own $250 micro ticket, while this audit prices the lead's own $1,000 ticket.
    The share count is sized ONCE at the highest reported rung so every rung is funded by
    the same quantity and no rung can be unfundable.
    """
    return int(ORDER_BUDGET // (float(price) * (1.0 + float(rung_bps) / 20_000.0)))

